def bottom_bar(tag, txt_lines, y=448, h=58):
    s = [rect(54, y, 852, h, fill=DARK, radius=8), rect(54, y, 4, h, fill=GOLD, radius=2),
         text(78, y+10, 400, 14, [tag], size=9, color=GOLD, bold=True, font=MONO, ls=1)]
    s.append(text(78, y+27, 812, 28, txt_lines, size=12.5, color=WHITE, bold=True, lh=1.4))
    return s

def two_col_layout(methods, cases, mc, cc):
    """左：方法4条；右：案例3张卡。"""
    s = []
    # 左栏
    s.append(rect(54, 118, 4, 18, fill=mc))
    s.append(text(66, 118, 380, 20, ["方法 · 我们会什么"], size=13.5, color=INK, bold=True))
    yy = 148
    for no, nm, ds in methods:
        s.append(text(54, yy, 30, 22, [no], size=14, color=mc, bold=True, font=MONO))
        s.append(text(90, yy+1, 380, 16, [nm], size=12, color=INK, bold=True))
        s.append(text(90, yy+20, 384, 44, [ds], size=10, color=INK2, lh=1.45))
        yy += 74
    # 右栏
    s.append(rect(496, 118, 4, 18, fill=cc))
    s.append(text(508, 118, 400, 20, ["应对 · 这些方法解决过什么"], size=13.5, color=INK, bold=True))
    yy = 148
    for nm, ds in cases:
        s.append(rect(496, yy, 410, 88, fill=MIST, radius=8))
        s.append(rect(496, yy, 4, 88, fill=cc, radius=2))
        s.append(text(514, yy+10, 380, 16, [nm], size=11.5, color=INK, bold=True))
        s.append(text(514, yy+32, 378, 52, [ds], size=10, color=INK2, lh=1.5))
        yy += 100
    return s

